<?php

namespace App\Services;

use Illuminate\Http\Response;
use Illuminate\Support\Carbon;
use Shuchkin\SimpleXLSXGen;

class ProfessionalSpreadsheetExportService
{
    private const NAVY = '#1D2D4F';

    private const ORANGE = '#E8470B';

    private const PALE_BLUE = '#EAF0F8';

    private const ZEBRA = '#F7F9FC';

    private const BORDER = '#CBD5E1';

    /**
     * @param  array<int, array{label: string, value: mixed}>  $metadata
     * @param  array<int, array{key: string, label: string, type?: string, width?: int|float}>  $columns
     * @param  iterable<int, array<string, mixed>>  $records
     */
    public function download(
        string $filename,
        string $businessName,
        string $reportTitle,
        array $metadata,
        array $columns,
        iterable $records,
        string $sheetName = 'Report'
    ): Response {
        $columnCount = max(1, count($columns));
        $lastColumn = $this->columnLetter($columnCount);
        $rows = [];

        $rows[] = [$this->styledText($businessName, self::NAVY, '#FFFFFF', 16, true, 'left', 28)];
        $rows[] = [$this->styledText($reportTitle, self::ORANGE, '#FFFFFF', 13, true, 'left', 24)];

        foreach ($metadata as $item) {
            $rows[] = [
                $this->styledText(mb_strtoupper((string) $item['label']), self::PALE_BLUE, self::NAVY, 9, true),
                $this->styledText($this->displayValue($item['value']), '#FFFFFF', '#334155', 9),
            ];
        }

        $rows[] = [];
        $headerRow = count($rows) + 1;
        $rows[] = array_map(
            fn (array $column) => $this->styledText($column['label'], self::NAVY, '#FFFFFF', 10, true, 'center', 24),
            $columns
        );

        $dataRow = 0;
        foreach ($records as $record) {
            $background = $dataRow % 2 === 0 ? '#FFFFFF' : self::ZEBRA;
            $row = [];

            foreach ($columns as $column) {
                $row[] = $this->formatCell(
                    $record[$column['key']] ?? null,
                    $column['type'] ?? 'text',
                    $background
                );
            }

            $rows[] = $row;
            $dataRow++;
        }

        if ($dataRow === 0) {
            $rows[] = [$this->styledText('No records matched the selected filters.', '#FFFFFF', '#64748B', 10, false, 'left', 22)];
        }

        $lastDataRow = count($rows);
        $xlsx = SimpleXLSXGen::fromArray($rows, mb_substr($sheetName, 0, 31))
            ->setDefaultFont('Arial')
            ->setDefaultFontSize(10)
            ->setTitle($reportTitle)
            ->setSubject($reportTitle)
            ->setAuthor($businessName)
            ->setCompany($businessName)
            ->setDescription('Generated by Acry-Link POS & Inventory System')
            ->setCategory('Business report')
            ->setLanguage('en-PH')
            ->mergeCells("A1:{$lastColumn}1")
            ->mergeCells("A2:{$lastColumn}2")
            ->freezePanes('A'.($headerRow + 1))
            ->autoFilter("A{$headerRow}:{$lastColumn}{$lastDataRow}");

        foreach ($metadata as $index => $_item) {
            if ($columnCount > 2) {
                $xlsx->mergeCells('B'.($index + 3).':'.$lastColumn.($index + 3));
            }
        }

        if ($dataRow === 0 && $columnCount > 1) {
            $xlsx->mergeCells('A'.$lastDataRow.':'.$lastColumn.$lastDataRow);
        }

        foreach ($columns as $index => $column) {
            $xlsx->setColWidth($index + 1, $column['width'] ?? 16);
        }

        return response((string) $xlsx, 200, [
            'Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            'Content-Disposition' => 'attachment; filename="'.str_replace('"', '', $filename).'"',
            'Cache-Control' => 'private, max-age=0, must-revalidate',
            'X-Content-Type-Options' => 'nosniff',
        ]);
    }

    private function formatCell(mixed $value, string $type, string $background): string
    {
        $common = ' bgcolor="'.$background.'" border="'.self::BORDER.'"';

        return match ($type) {
            'integer' => '<style'.$common.' nf="0"><right>'.(int) ($value ?? 0).'</right></style>',
            'decimal' => '<style'.$common.' nf="#,##0.00"><right>'.(float) ($value ?? 0).'</right></style>',
            'currency' => '<style'.$common.' nf="₱#,##0.00;[Red]-₱#,##0.00"><right>'.(float) ($value ?? 0).'</right></style>',
            'date' => $value
                ? '<style'.$common.' nf="mmm d, yyyy"><center>'.$this->dateValue($value).'</center></style>'
                : $this->styledText('', $background, '#334155', 10, false, 'center'),
            'time' => $this->styledText($this->timeValue($value), $background, '#334155', 10, false, 'center'),
            'status' => $this->styledText($this->displayValue($value), $background, self::NAVY, 10, true, 'center'),
            default => $this->styledText($this->displayValue($value), $background, '#334155', 10, false, 'left', null, true),
        };
    }

    private function styledText(
        string $value,
        string $background,
        string $color,
        int $fontSize,
        bool $bold = false,
        string $align = 'left',
        ?int $height = null,
        bool $wrap = false
    ): string {
        $value = preg_replace('/[\r\n]+/u', ' ', $value) ?? $value;
        $safe = htmlspecialchars($this->safeSpreadsheetText($value), ENT_NOQUOTES | ENT_XML1, 'UTF-8');
        $attributes = ' bgcolor="'.$background.'" color="'.$color.'" border="'.self::BORDER.'" font-size="'.$fontSize.'"';

        if ($height !== null) {
            $attributes .= ' height="'.$height.'"';
        }

        $content = '<raw>'.$safe.'</raw>';
        $content = $bold ? '<b>'.$content.'</b>' : $content;
        $content = $wrap ? '<wraptext>'.$content.'</wraptext>' : $content;
        $content = '<'.$align.'>'.$content.'</'.$align.'>';

        return '<style'.$attributes.'><middle>'.$content.'</middle></style>';
    }

    private function safeSpreadsheetText(string $value): string
    {
        return preg_match('/^[=+\-@]/u', $value) ? "'".$value : $value;
    }

    private function displayValue(mixed $value): string
    {
        if ($value === null) {
            return '';
        }

        if ($value instanceof \DateTimeInterface) {
            return Carbon::instance($value)->format('M j, Y g:i A');
        }

        return (string) $value;
    }

    private function dateValue(mixed $value): int
    {
        $date = Carbon::parse($value)->startOfDay();
        $excelEpoch = Carbon::create(1899, 12, 30, 0, 0, 0, $date->timezone);

        return (int) $excelEpoch->diffInDays($date);
    }

    private function timeValue(mixed $value): string
    {
        if (! filled($value)) {
            return '';
        }

        try {
            return Carbon::parse((string) $value)->format('g:i A');
        } catch (\Throwable) {
            return (string) $value;
        }
    }

    private function columnLetter(int $column): string
    {
        $letter = '';

        while ($column > 0) {
            $column--;
            $letter = chr(65 + ($column % 26)).$letter;
            $column = intdiv($column, 26);
        }

        return $letter;
    }
}
