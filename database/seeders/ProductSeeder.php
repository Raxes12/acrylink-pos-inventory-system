class ProductSeeder extends Seeder
{
    public function run(): void
    {
        foreach ($this->normalizedRows() as $index => $row) {
            $this->assertNormalizedRow($row, $index);

            $variantCode = $row['VARIANT CODE'] ?? $this->variantCodeFor($row, $index);
            $product = $this->productFromRow($row, $variantCode);
            $variant = $this->variantFromRow($row, $product, $variantCode);
            $this->stockFromRow($row, $variant);
        }
    }

    private function productFromRow(array $row, string $variantCode): Product
    {
        $existingVariant = ProductVariant::with('product')
            ->where('variant_code', $variantCode)
            ->first();

        $product = $existingVariant?->product ?: Product::firstOrNew([
            'name' => $row['DESCRIPTION / PRODUCT NAME'],
        ]);

        $product->fill([
            'name' => $row['DESCRIPTION / PRODUCT NAME'],
            'category' => $row['CATEGORY'] ?? 'Other',
            'description' => $row['DESCRIPTION NOTES'] ?? null,
            'status' => 'active',
        ]);
        $product->save();

        return $product;
    }

    private function variantFromRow(array $row, Product $product, string $variantCode): ProductVariant
    {
        return ProductVariant::updateOrCreate(
            ['variant_code' => $variantCode],
            [
                'product_id' => $product->id,
                'brand_id' => $this->brandId($row['BRAND'] ?? null),
                'unit_id' => Unit::idForCode($row['UOM'] ?? null),
                'supplier_id' => $this->supplierId($row['SUPPLIER/REMARKS'] ?? null),
                'barcode' => $row['BARCODE'] ?? null,
                'part_number' => $row['PART NUMBER'] ?? null,
                'size' => $row['SIZE'] ?? null,
                'color' => $row['COLOR'] ?? null,
                'selling_price' => $this->money($row['SELLING PRICE'] ?? 0),
                'cost_price' => $this->money($row['COST PRICE'] ?? 0),
                'status' => 'active',
            ]
        );
    }

    private function stockFromRow(array $row, ProductVariant $variant): InventoryStock
    {
        $minimumStock = (int) ($row['MINIMUM STOCK'] ?? 0);

        return InventoryStock::updateOrCreate(
            ['variant_id' => $variant->id],
            [
                'quantity_on_hand' => (int) ($row['QUANTITY'] ?? 0),
                'minimum_stock' => $minimumStock,
                'critical_stock' => max(0, (int) floor($minimumStock / 2)),
            ]
        );
    }

    private function brandId(?string $name): ?int
    {
        $name = trim((string) $name);

        return $name === ''
            ? null
            : Brand::firstOrCreate(['name' => $name])->id;
    }

    private function supplierId(?string $name): ?int
    {
        $name = trim((string) $name);

        if ($name === '') {
            return null;
        }

        return Supplier::firstOrCreate(
            ['name' => $name],
            ['status' => 'active', 'payment_method' => 'cash']
        )->id;
    }

    private function variantCodeFor(array $row, int $index): string
    {
        $base = $row['PART NUMBER'] ?? $row['DESCRIPTION / PRODUCT NAME'] ?? 'variant';

        return Str::upper(Str::slug($base, '-')).'-'.str_pad((string) ($index + 1), 3, '0', STR_PAD_LEFT);
    }

    private function money(mixed $value): float
    {
        return (float) preg_replace('/[^0-9.]/', '', (string) $value);
    }

    private function assertNormalizedRow(array $row, int $index): void
    {
        $unexpectedNumericKeys = array_filter(array_keys($row), 'is_int');

        if ($unexpectedNumericKeys !== []) {
            $rowNumber = $index + 1;

            throw new \InvalidArgumentException(
                "ProductSeeder row {$rowNumber} has unexpected numeric values. ".
                'If a money value has a comma, wrap it in quotes, for example "2,173.50".'
            );
        }
    }

